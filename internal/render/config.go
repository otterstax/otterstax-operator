// Package render turns a server spec and its connections into the single
// config.yaml the OtterStax server reads at startup.
//
// The YAML is written by hand rather than marshalled from structs. That is
// deliberate. The server's parser has a family of behaviours where a document
// parses cleanly and means something other than intended, and the defence
// against all of them is a rule about the OUTPUT — every string is quoted,
// always — which a struct marshaller applies only incidentally. Writing the
// bytes makes the rule structural.
//
// The behaviours this guards against were established by reading the parser and
// by running a probe linked against the same yaml-cpp:
//
//   - A bare key (password:) or an unquoted ~ / null / Null / NULL does not
//     produce an empty string and does not throw. yaml-cpp has an explicit
//     as_if<std::string> specialisation returning the four-character string
//     "null". So `password:` is a password, `alias:` is a connection named
//     null that passes validation, and `schema:` defeats the "public" default.
//   - An unquoted value containing " #" is truncated at the hash.
//   - Unquoted yes/no/on/off and bare numerics change type on the way in.
//
// Quoting every string closes all of them with one rule.
package render

import (
	"errors"
	"fmt"
	"sort"
	"strings"

	v1alpha1 "github.com/otterstax/otterstax-operator/api/v1alpha1"
)

// Input is everything the rendered config depends on. Nothing else may
// influence the output: no clock, no environment, no map iteration order.
type Input struct {
	Service         v1alpha1.ServiceSpec
	ConnectionRetry v1alpha1.ConnectionRetrySpec
	Connections     []v1alpha1.OtterStaxConnection
}

// Render produces config.yaml. It is a pure function of Input: the same Input
// yields byte-identical output, always. A renderer that drifts would restart
// the server, and a restart here is a SIGKILL in the middle of a WAL write, not
// an inconvenience.
func Render(in Input) ([]byte, error) {
	if err := validate(in); err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("# Generated by otterstax-operator. Do not edit.\n")
	b.WriteString("#\n")
	b.WriteString("# The server reads this file once at startup and has no reload path,\n")
	b.WriteString("# so every change here arrives as a process restart.\n")
	b.WriteString("\n")

	writeService(&b, in.Service, in.ConnectionRetry)
	writeConnections(&b, in.Connections)

	return []byte(b.String()), nil
}

// validate refuses to render rather than emitting something that parses.
//
// The server cannot help here: it accepts duplicate aliases (last wins, and the
// earlier connection is opened and then leaked), and a duplicate alias ACROSS
// backend kinds routes queries to whichever kind is probed first. Both are
// silent. So the check has to live here.
func validate(in Input) error {
	var errs []error

	seen := make(map[string]int, len(in.Connections))
	for i, c := range in.Connections {
		if c.Spec.Alias == "" {
			errs = append(errs, fmt.Errorf("connection %q: empty alias", c.Name))
			continue
		}
		if j, dup := seen[c.Spec.Alias]; dup {
			errs = append(errs, fmt.Errorf(
				"alias %q is used by both %q and %q; the server would silently keep one and leak the other",
				c.Spec.Alias, in.Connections[j].Name, c.Name))
			continue
		}
		seen[c.Spec.Alias] = i

		if err := validateBackend(c); err != nil {
			errs = append(errs, fmt.Errorf("connection %q: %w", c.Name, err))
		}
	}
	return errors.Join(errs...)
}

// validateBackend enforces the fields the server requires. An entry missing one
// of them makes the parser throw and the process exit 1, which is at least
// loud — but failing here is better, because it never reaches a pod.
func validateBackend(c v1alpha1.OtterStaxConnection) error {
	switch {
	case c.Spec.MySQL != nil:
		return requireSQL("mysql", c.Spec.MySQL)
	case c.Spec.ClickHouse != nil:
		return requireSQL("clickhouse", c.Spec.ClickHouse)
	case c.Spec.PostgreSQL != nil:
		p := c.Spec.PostgreSQL
		return requireAll("postgresql", map[string]string{
			"host": p.Host, "username": p.Username, "database": p.Database,
		})
	case c.Spec.S3 != nil:
		s := c.Spec.S3
		if strings.Contains(s.Endpoint, "://") {
			return fmt.Errorf("s3: endpoint %q carries a scheme; the server forces plain HTTP and path-style addressing when endpoint is set", s.Endpoint)
		}
		return requireAll("s3", map[string]string{
			"accessKey": s.AccessKey, "secretKey": s.SecretKey,
		})
	default:
		return errors.New("no backend set")
	}
}

func requireSQL(kind string, b *v1alpha1.SQLBackend) error {
	return requireAll(kind, map[string]string{
		"host": b.Host, "username": b.Username, "database": b.Database,
	})
}

func requireAll(kind string, fields map[string]string) error {
	missing := make([]string, 0, len(fields))
	for k, v := range fields {
		if strings.TrimSpace(v) == "" {
			missing = append(missing, k)
		}
	}
	if len(missing) == 0 {
		return nil
	}
	sort.Strings(missing) // map iteration is random; the message must not be
	return fmt.Errorf("%s: missing required %s", kind, strings.Join(missing, ", "))
}

func writeService(b *strings.Builder, s v1alpha1.ServiceSpec, r v1alpha1.ConnectionRetrySpec) {
	b.WriteString("service:\n")
	b.WriteString("  flight_sql:\n")
	fmt.Fprintf(b, "    port: %d\n", s.FlightSQLPort)
	b.WriteString("  mysql:\n")
	fmt.Fprintf(b, "    port: %d\n", s.MySQLPort)
	b.WriteString("  postgres:\n")
	fmt.Fprintf(b, "    port: %d\n", s.PostgresPort)
	b.WriteString("  spark_connect:\n")
	fmt.Fprintf(b, "    port: %d\n", s.SparkConnectPort)
	// Emitted even at its defaults, like schema: "public" — so the server's
	// own default is never load-bearing.
	b.WriteString("  connection_retry:\n")
	fmt.Fprintf(b, "    max_attempts: %d\n", r.MaxAttempts)
	fmt.Fprintf(b, "    delay_ms: %d\n", r.DelayMilliseconds)
	b.WriteString("\n")
}

// writeConnections emits the backends grouped by kind.
//
// Section order is fixed, and entry order within a section follows the input
// slice rather than being sorted. Sorting would be a silent behaviour change:
// with a duplicate alias across kinds the server resolves by probe order, so
// reordering entries can reroute a query to a different backend.
func writeConnections(b *strings.Builder, conns []v1alpha1.OtterStaxConnection) {
	var mysql, pg, ch, s3 []v1alpha1.OtterStaxConnection
	for _, c := range conns {
		switch {
		case c.Spec.MySQL != nil:
			mysql = append(mysql, c)
		case c.Spec.PostgreSQL != nil:
			pg = append(pg, c)
		case c.Spec.ClickHouse != nil:
			ch = append(ch, c)
		case c.Spec.S3 != nil:
			s3 = append(s3, c)
		}
	}

	// An empty connections: block is not the same as no block, but both yield
	// zero connections. Omitting it entirely is the honest encoding.
	if len(mysql)+len(pg)+len(ch)+len(s3) == 0 {
		return
	}

	b.WriteString("connections:\n")

	if len(mysql) > 0 {
		b.WriteString("  mysql:\n")
		for _, c := range mysql {
			m := c.Spec.MySQL
			writeSQLEntry(b, c.Spec.Alias, m.Host, m.Port, m.Username, m.Password, m.Database, "", m.Table)
		}
	}
	if len(pg) > 0 {
		b.WriteString("  postgresql:\n")
		for _, c := range pg {
			p := c.Spec.PostgreSQL
			schema := p.Schema
			if schema == "" {
				// Emitted explicitly rather than relying on the parser's default,
				// so that the default is never load-bearing and never silently
				// changes underneath us.
				schema = "public"
			}
			writeSQLEntry(b, c.Spec.Alias, p.Host, p.Port, p.Username, p.Password, p.Database, schema, p.Table)
		}
	}
	if len(ch) > 0 {
		b.WriteString("  clickhouse:\n")
		for _, c := range ch {
			h := c.Spec.ClickHouse
			writeSQLEntry(b, c.Spec.Alias, h.Host, h.Port, h.Username, h.Password, h.Database, "", h.Table)
		}
	}
	if len(s3) > 0 {
		b.WriteString("  s3:\n")
		for _, c := range s3 {
			s := c.Spec.S3
			fmt.Fprintf(b, "    - alias: %s\n", q(c.Spec.Alias))
			fmt.Fprintf(b, "      access_key: %s\n", q(s.AccessKey))
			fmt.Fprintf(b, "      secret_key: %s\n", q(s.SecretKey))
			writeOptional(b, "      region", s.Region)
			writeOptional(b, "      session_token", s.SessionToken)
			writeOptional(b, "      endpoint", s.Endpoint)
		}
	}
}

// writeSQLEntry emits one backend. Key order matches every config shipped with
// the server; port is a quoted string because that is what the parser reads for
// backends, unlike the server's own listener ports which are integers.
func writeSQLEntry(b *strings.Builder, alias, host string, port int32, user, pass, db, schema, table string) {
	fmt.Fprintf(b, "    - alias: %s\n", q(alias))
	fmt.Fprintf(b, "      host: %s\n", q(host))
	if port != 0 {
		fmt.Fprintf(b, "      port: %s\n", q(fmt.Sprintf("%d", port)))
	}
	fmt.Fprintf(b, "      username: %s\n", q(user))
	fmt.Fprintf(b, "      password: %s\n", q(pass))
	fmt.Fprintf(b, "      database: %s\n", q(db))
	if schema != "" {
		fmt.Fprintf(b, "      schema: %s\n", q(schema))
	}
	fmt.Fprintf(b, "      table: %s\n", q(table))
}

// writeOptional omits the key entirely when the value is empty. It never emits
// a bare key: that would be read as the literal string "null".
func writeOptional(b *strings.Builder, key, value string) {
	if value == "" {
		return
	}
	fmt.Fprintf(b, "%s: %s\n", key, q(value))
}

// q renders a YAML double-quoted scalar. Every string in the connections block
// goes through it, unconditionally — see the package comment for why.
func q(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\x%02x`, r)
				continue
			}
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
